// Turns the Hugeicons SVGs exported from our Figma library (design/hugeicons/*.svg)
// into React components in src/components/icons/hugeicons.tsx.
//
// Usually run for you by scripts/fetch-figma-icons.mjs. To add an icon, add
// its Figma node ids to design/hugeicons/manifest.json and fetch again, or
// export its "Style=Solid, Type=Rounded" component from the Figma file
// "HC - Huge Icon" (page "❖ Hugeicons Pro") as design/hugeicons/<icon-name>.svg
// and run:
//
//   node scripts/build-icons.mjs

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("../design/hugeicons/", import.meta.url);
const OUT = new URL("../src/components/icons/hugeicons.tsx", import.meta.url);
const ICON_COLOR = /#141B34/gi;

const ATTRS = {
  d: "d",
  cx: "cx",
  cy: "cy",
  r: "r",
  rx: "rx",
  ry: "ry",
  x: "x",
  y: "y",
  x1: "x1",
  y1: "y1",
  x2: "x2",
  y2: "y2",
  width: "width",
  height: "height",
  points: "points",
  transform: "transform",
  fill: "fill",
  opacity: "opacity",
  "fill-opacity": "fillOpacity",
  stroke: "stroke",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
};

function pascal(name) {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
}

function extract(svg, file) {
  // Exports that include the Figma page around the icon carry a
  // `<g id="Style=…, Type=Rounded">` group: keep only that. Plain exports
  // (scripts/fetch-figma-icons.mjs) are just the icon. Clip-path <defs> are
  // not part of the artwork.
  const group = svg.search(/<g id="Style=[^"]*, Type=Rounded">/);
  const body = (group >= 0 ? svg.slice(group) : svg).replace(/<defs>[\s\S]*?<\/defs>/g, "");
  const shapes = [];
  for (const m of body.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*?)\/?>/g)) {
    const props = {};
    for (const a of m[2].matchAll(/([a-z-]+)="([^"]*)"/g)) {
      const key = ATTRS[a[1]];
      if (key) props[key] = a[2].replace(ICON_COLOR, "currentColor");
    }
    shapes.push([m[1], props]);
  }
  if (!shapes.length) throw new Error(`${file}: no shapes found`);
  return shapes;
}

const files = readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort();
const icons = files.map((f) => {
  const name = f.replace(/\.svg$/, "");
  return { name, component: `${pascal(name)}Icon`, shapes: extract(readFileSync(new URL(f, SRC), "utf8"), f) };
});

const out = `// Generated by scripts/build-icons.mjs from design/hugeicons/*.svg. Do not edit by hand.
// Source: Figma "HC - Huge Icon", page "❖ Hugeicons Pro", Type=Rounded.

import { createElement, type SVGProps } from "react";

type Shape = [string, Record<string, string>];

export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  /** Width and height in px. Defaults to 24. */
  size?: number | string;
  /** Overrides the stroke width (Hugeicons use 1.5 at 24px). */
  strokeWidth?: number | string;
};

function make(displayName: string, shapes: Shape[]) {
  function Icon({ size = 24, strokeWidth, ...rest }: IconProps) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg" {...rest}>
        {shapes.map(([tag, props], i) =>
          createElement(tag, { key: i, ...props, ...(strokeWidth !== undefined && props.strokeWidth ? { strokeWidth } : {}) }),
        )}
      </svg>
    );
  }
  Icon.displayName = displayName;
  return Icon;
}

${icons
  .map((i) => `/** Hugeicons "${i.name}" */\nexport const ${i.component} = make("${i.component}", ${JSON.stringify(i.shapes)});`)
  .join("\n\n")}
`;

writeFileSync(OUT, out);

// src/components/icons/index.ts: the names the app imports, from the manifest.
// Icons whose SVG hasn't been fetched yet fall back to lucide-react.
const manifest = JSON.parse(readFileSync(new URL("../design/hugeicons/manifest.json", import.meta.url), "utf8"));
const built = new Map(icons.map((i) => [i.name, i]));
const fromFigma = [];
const fromLucide = [];
for (const entry of manifest.icons) {
  if (built.has(entry.name)) fromFigma.push(`  ${built.get(entry.name).component} as ${entry.as},`);
  else if (entry.fallback) fromLucide.push(`  ${entry.fallback} as ${entry.as},`);
  else throw new Error(`${entry.name}: no SVG in design/hugeicons/ and no fallback`);
}
const index = `// Generated by scripts/build-icons.mjs from design/hugeicons/manifest.json. Do not edit by hand.
// Every icon in the app comes from here, named by what it means.

export type { IconProps } from "./hugeicons";
export {
${fromFigma.sort().join("\n")}
} from "./hugeicons";
${
  fromLucide.length
    ? `
// Not fetched from Figma yet: run scripts/fetch-figma-icons.mjs to replace these.
export {
${fromLucide.sort().join("\n")}
} from "lucide-react";
`
    : ""
}`;
writeFileSync(new URL("../src/components/icons/index.ts", import.meta.url), index);

const isStroke = (i) => i.shapes.some(([, p]) => p.stroke && p.stroke !== "none" && (!p.fill || p.fill === "none"));
const strokeCount = icons.filter(isStroke).length;
console.log(`Built ${icons.length} icons (${icons.length - strokeCount} solid, ${strokeCount} stroke) into src/components/icons/`);
for (const i of icons) console.log(`  ${isStroke(i) ? "stroke" : "solid "}  ${i.name}`);
if (fromLucide.length) console.log(`Still using lucide-react for: ${fromLucide.map((l) => l.trim().split(" as ")[1].replace(",", "")).join(", ")}`);
